ROOT = Path(__file__).resolve().parents[2]
DATA = {}
CURRENT = None

def topic(number, choice, instruction, levels, score_instruction):
    global CURRENT
    CURRENT = f'T{number:04d}'
    DATA[CURRENT] = {'rows': [], 'choice': choice, 'instruction': instruction,
                     'levels': levels, 'score_instruction': score_instruction}

def row(slot, state, specs):
    cfg = DATA[CURRENT]
    questions, labels, evidence = {}, {}, {}
    for key, kind, instruction, criteria, values, ev in specs:
        q = {'type': kind, 'instructions': instruction}
        if criteria is not None:
            q['criteria'] = criteria
        questions[key] = q
        labels[key] = {'noul': values} if kind == 'noul' else {'probabilities': dict(zip(criteria if kind == 'choice' else map(str, range(len(criteria))), values))}
        evidence[key] = ev
    cfg['rows'].append({'sample_id': f'{CURRENT}-{slot:02d}', 'topic_id': CURRENT,
                       'slot': slot, 'request': {'model': 'jev-latest', 'state': state, 'questions': questions},
                       'labels': labels, 'review': {'case_type': CASE_TYPES[slot],
                       'evidence': evidence, 'label_source': 'agent_synthetic'}})

def C(slot, state, values, ev, instruction=None, criteria=None):
    cfg = DATA[CURRENT]
    text = instruction or cfg['instruction']
    if slot == 1:
        text = {'任务': text, '范围': '只依据当前状态中已提供的事实作判断。'}
    row(slot, state, [('判断', 'choice', text, criteria or cfg['choice'], values, ev)])

def S(slot, state, values, ev, instruction=None, levels=None):
    cfg = DATA[CURRENT]
    row(slot, state, [('程度', 'score', instruction or cfg['score_instruction'], levels or cfg['levels'], values, ev)])

def N(slot, state, instruction, value, ev):
    row(slot, state, [('核验', 'noul', instruction, None, value, ev)])

def M(state, cv, ce, sv, se, ni, nv, ne, ci=None, si=None, choices=None, levels=None):
    cfg = DATA[CURRENT]
    row(10, state, [
        ('类别', 'choice', ci or cfg['instruction'], choices or cfg['choice'], cv, ce),
        ('程度', 'score', si or cfg['score_instruction'], levels or cfg['levels'], sv, se),
        ('核验', 'noul', ni, None, nv, ne)])


