def apply_medium():
    """把每题的中档 state 与对应依据写入 ROWS；在序列化之前调用。

    条目为 (槽位, state, 依据覆盖) 或 (槽位, state, 依据覆盖, 说明覆盖)。
    """
    for topic_id, spec in MEDIUM.items():
        slot, state, evidence = spec[0], spec[1], spec[2]
        instructions = spec[3] if len(spec) > 3 else {}
        matched = [r for r in ROWS[topic_id] if r["slot"] == slot]
        if len(matched) != 1:
            raise ValueError(f"{topic_id} 槽位 {slot} 不唯一")
        entry = matched[0]
        entry["request"]["state"] = state
        if set(evidence) != set(entry["review"]["evidence"]):
            raise ValueError(f"{topic_id} 槽位 {slot} 的依据键不匹配")
        entry["review"]["evidence"].update(evidence)
        for key, value in instructions.items():
            entry["request"]["questions"][key]["instructions"] = value


def write_draft(topic_id):
    """把十行草稿写入 data/drafts，供长度实测使用。"""
    apply_medium()
    rows = sorted(ROWS[topic_id], key=lambda r: r["slot"])
    if [r["slot"] for r in rows] != list(range(1, 11)):
        raise ValueError(f"{topic_id} 槽位不全")
    write_jsonl(ROOT / "data/drafts" / f"{topic_id}.jsonl", rows)


def save(topic_id):
    """写草稿并立即发布为正式分片；已存在的分片不覆盖。"""
    shard = ROOT / "data/shards" / f"{topic_id}.jsonl"
    if shard.exists():
        raise FileExistsError(f"已存在正式分片，先核对再处理: {shard}")
    write_draft(topic_id)
    draft = ROOT / "data/drafts" / f"{topic_id}.jsonl"
    subprocess.run([sys.executable, "-m", "scripts.finalize_shard", str(draft)], cwd=ROOT, check=True)


if __name__ == "__main__":
    arguments = sys.argv[1:]
    if arguments[:1] == ["drafts"]:
        for name in arguments[1:] or sorted(ROWS):
            write_draft(name)
    else:
        for name in arguments or sorted(ROWS):
            save(name)
