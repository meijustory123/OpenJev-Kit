DATA = {}
CONFIG = {}

def topic(number, rule, cq, options, sq, levels):
    global T
    T = f'T{number:04d}'
    DATA[T] = []
    CONFIG[T] = (rule, cq, dict(options), sq, levels)

def distribution(keys, best, strength):
    rest = round((1-strength)/(len(keys)-1), 3)
    result = {key: rest for key in keys}
    result[best] = round(1-rest*(len(keys)-1), 3)
    return result

def append(slot, record, parts):
    rule, cq, options, sq, levels = CONFIG[T]
    state = {'判定约定': rule, '现场记录': record}
    if slot == 2:
        state = [{'项目': '本场判定约定', '内容': rule}, {'项目': '本次现场记录', '内容': record}]
    qs, labels, evidence = {}, {}, {}
    for kind, target, reason, extra in parts:
        key = {'choice':'记录分类','score':'核对等级','noul':'事实核验'}[kind]
        if kind == 'choice':
            opts = dict(options)
            inst = cq
            if slot == 1:
                inst = {'评估对象':'本次现场记录', '判断维度':cq, '范围':'仅采用随记录提供的判定约定'}
                first = next(iter(opts))
                opts[first] = {'适用边界': opts[first]}
            qs[key] = {'type':kind,'instructions':inst,'criteria':opts}
            strength = extra if extra is not None else {1:.97,2:.94,3:.96,4:.95,10:.93}[slot]
            labels[key] = {'probabilities':distribution(list(opts),target,strength)}
        elif kind == 'score':
            qs[key] = {'type':kind,'instructions':sq,'criteria':levels}
            labels[key] = {'probabilities':dict(zip(map(str,range(len(levels))),extra))}
        else:
            qs[key] = {'type':kind,'instructions':extra}
            labels[key] = {'noul':target}
        evidence[key] = reason
    DATA[T].append({'sample_id':f'{T}-{slot:02d}','topic_id':T,'slot':slot,
        'request':{'model':'jev-latest','state':state,'questions':qs},'labels':labels,
        'review':{'case_type':CASE_TYPES[slot],'evidence':evidence,'label_source':'agent_synthetic'}})

def c(slot, state, best, reason, strength=None): append(slot,state,[('choice',best,reason,strength)])
def s(slot, state, probs, reason): append(slot,state,[('score',None,reason,probs)])
def n(slot, state, question, prob, reason): append(slot,state,[('noul',prob,reason,question)])
def m(state, best, cr, probs, sr, question, prob, nr):
    append(10,state,[('choice',best,cr,None),('score',None,sr,probs),('noul',prob,nr,question)])

