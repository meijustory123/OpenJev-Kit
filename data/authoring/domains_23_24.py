def apply_medium():
    """把每题的中档 state 与对应依据写入 ROWS；在序列化之前调用。

    条目为 (槽位, state, 依据覆盖)，依据覆盖的键必须与本题槽位的问题 ID 一致。
    """
    for topic, spec in MEDIUM.items():
        slot, state, evidence = spec[0], spec[1], spec[2]
        matched = [r for r in ROWS[topic] if r["slot"] == slot]
        if len(matched) != 1:
            raise ValueError(f"{topic} 槽位 {slot} 不唯一")
        target = matched[0]
        target["request"]["state"] = state
        if set(evidence) != set(target["review"]["evidence"]):
            raise ValueError(f"{topic} 槽位 {slot} 的依据键不匹配")
        target["review"]["evidence"].update(evidence)


def write_draft(topic):
    """把十行草稿写入 data/drafts，供长度实测使用。"""
    apply_medium()
    rows = sorted(ROWS[topic], key=lambda r: r["slot"])
    if [r["slot"] for r in rows] != list(range(1, 11)):
        raise ValueError(f"{topic} 槽位不全")
    write_jsonl(ROOT / "data/drafts" / f"{topic}.jsonl", rows)


def save(topic):
    """写草稿并立即发布为正式分片；已存在的分片不覆盖。"""
    shard = ROOT / "data/shards" / f"{topic}.jsonl"
    if shard.exists():
        raise FileExistsError(f"已存在正式分片，先核对再处理: {shard}")
    write_draft(topic)
    draft = ROOT / "data/drafts" / f"{topic}.jsonl"
    subprocess.run([sys.executable, "-m", "scripts.finalize_shard", str(draft)], cwd=ROOT, check=True)


def measure(topics):
    """本地 tokenizer 逐题实测，打印每个槽位的完整候选输入长度。"""
    apply_medium()
    tokenizer = get_tokenizer("Qwen3.5-0.8B")
    for topic in topics:
        for row_ in sorted(ROWS[topic], key=lambda r: r["slot"]):
            request = parse_request(row_["request"])
            longest = 0
            for question in request.questions.values():
                encoded, _ = encode_candidates(tokenizer, request.state, question, 8192)
                longest = max(longest, max(len(ids) for ids in encoded["input_ids"]))
            band = "短" if longest <= 512 else "中" if longest <= 1024 else "超限"
            print(topic, row_["slot"], longest, band, len(json.dumps(request.state, ensure_ascii=False)))


def report():
    counts = Counter()
    for rows in ROWS.values():
        for row_ in rows:
            for label in row_["labels"].values():
                counts["noul" if "noul" in label else "vector"] += 1
    print(json.dumps({"topics": len(ROWS), "rows": sum(len(v) for v in ROWS.values()),
                      "labels": counts}, ensure_ascii=False))


