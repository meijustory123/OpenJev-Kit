def check_probabilities():
    """概率和必须为 1；发布前自检，避免 finalize_shard 才发现问题。"""
    for topic in sorted(ROWS):
        for entry in ROWS[topic]:
            for key, value in entry["labels"].items():
                if "probabilities" not in value:
                    continue
                total = round(sum(value["probabilities"].values()), 9)
                if abs(total - 1) > 1e-9:
                    raise ValueError(f"{entry['sample_id']} 问题 {key} 概率和为 {total}")


def write_draft(topic):
    """把十行草稿写入 data/drafts，供长度实测使用。"""
    check_probabilities()
    rows = sorted(ROWS[topic], key=lambda r: r["slot"])
    if [r["slot"] for r in rows] != list(range(1, 11)):
        raise ValueError(f"{topic} 槽位不全")
    write_jsonl(ROOT / "data/drafts" / f"{topic}.jsonl", rows)


def save(topic):
    """写草稿并立即发布为正式分片；已存在的分片不覆盖。"""
    shard = ROOT / "data/shards" / f"{topic}.jsonl"
    if shard.exists():
        raise FileExistsError(f"已存在正式分片，先核对再处理: {shard}")
    write_draft(topic)
    draft = ROOT / "data/drafts" / f"{topic}.jsonl"
    subprocess.run([sys.executable, "-m", "scripts.finalize_shard", str(draft)], cwd=ROOT, check=True)


def measure(topic):
    """逐题实测长度档位，发布前检查 9 短 1 中。"""
    write_draft(topic)
    draft = ROOT / "data/drafts" / f"{topic}.jsonl"
    subprocess.run([sys.executable, "-m", "scripts.draft_lengths", str(draft), "--enforce-mix"],
                   cwd=ROOT, check=False)


if __name__ == "__main__":
    arguments = sys.argv[1:]
    if arguments[:1] == ["drafts"]:
        for name in arguments[1:] or sorted(ROWS):
            write_draft(name)
    elif arguments[:1] == ["measure"]:
        for name in arguments[1:] or sorted(ROWS):
            measure(name)
    else:
        for name in arguments or sorted(ROWS):
            save(name)
