ROWS = {}


def c(instructions, criteria, probabilities, evidence):
    return ({"type": "choice", "instructions": instructions, "criteria": criteria},
            {"probabilities": dict(zip(criteria, probabilities))}, evidence)


def s(instructions, criteria, probabilities, evidence):
    return ({"type": "score", "instructions": instructions, "criteria": criteria},
            {"probabilities": dict(zip(map(str, range(len(criteria))), probabilities))}, evidence)


def n(instructions, value, evidence):
    return ({"type": "noul", "instructions": instructions}, {"noul": value}, evidence)


def row(topic, slot, state, *questions):
    keys = ["类别", "程度", "事实"] if slot == 10 else ["判断"]
    ROWS.setdefault(topic, []).append({
        "sample_id": f"{topic}-{slot:02d}", "topic_id": topic, "slot": slot,
        "request": {"model": "jev-latest", "state": state,
                    "questions": {k: q[0] for k, q in zip(keys, questions)}},
        "labels": {k: q[1] for k, q in zip(keys, questions)},
        "review": {"case_type": CASE_TYPES[slot],
                   "evidence": {k: q[2] for k, q in zip(keys, questions)},
                   "label_source": "agent_synthetic"}})


