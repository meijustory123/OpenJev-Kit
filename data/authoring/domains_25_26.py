def apply_medium():
    """把每题的中档 state 与对应依据写入 ROWS；在序列化之前调用。"""
    for topic, spec in MEDIUM.items():
        slot, state, evidence = spec
        matched = [r for r in ROWS[topic] if r["slot"] == slot]
        if len(matched) != 1:
            raise ValueError(f"{topic} 槽位 {slot} 不唯一")
        row = matched[0]
        row["request"]["state"] = state
        if set(evidence) != set(row["review"]["evidence"]):
            raise ValueError(f"{topic} 槽位 {slot} 的依据键不匹配")
        row["review"]["evidence"].update(evidence)


def write_draft(topic):
    """把十行草稿写入 data/drafts，供长度实测使用。"""
    apply_medium()
    rows = sorted(ROWS[topic], key=lambda r: r["slot"])
    if [r["slot"] for r in rows] != list(range(1, 11)):
        raise ValueError(f"{topic} 槽位不全")
    write_jsonl(ROOT / "data/drafts" / f"{topic}.jsonl", rows)


def measured(topic):
    """发布前对本题十条逐一实测最长完整候选输入 token。"""
    from openjev.model import get_tokenizer, encode_candidates
    from openjev.protocol import parse_request
    tokenizer = get_tokenizer("Qwen3.5-0.8B")
    result = {}
    for row in sorted(ROWS[topic], key=lambda r: r["slot"]):
        request = parse_request(row["request"])
        lengths = [max(len(ids) for ids in encode_candidates(tokenizer, request.state, q, 8192)[0]["input_ids"])
                   for q in request.questions.values()]
        result[row["slot"]] = max(lengths)
    short = [s for s, t in result.items() if t <= 512]
    medium = [s for s, t in result.items() if 513 <= t <= 1024]
    if len(short) != 9 or len(medium) != 1:
        raise ValueError(f"{topic} 不是9短1中：{result}")
    return result


def save(topic):
    """写草稿并立即发布为正式分片；已存在的分片不覆盖。"""
    shard = ROOT / "data/shards" / f"{topic}.jsonl"
    if shard.exists():
        raise FileExistsError(f"已存在正式分片，先核对再处理: {shard}")
    write_draft(topic)
    draft = ROOT / "data/drafts" / f"{topic}.jsonl"
    subprocess.run([sys.executable, "-m", "scripts.finalize_shard", str(draft)], cwd=ROOT, check=True)


def report():
    """汇总本批的结构化覆盖与中档槽位，供交付报告使用。"""
    apply_medium()
    arrays, instrs, descs, medium, mixed_uncertain = 0, 0, 0, {}, 0
    for topic, rows in sorted(ROWS.items()):
        for row in rows:
            if isinstance(row["request"]["state"], (list, dict)):
                arrays += 1
            for question in row["request"]["questions"].values():
                if isinstance(question["instructions"], (list, dict)):
                    instrs += 1
                if question["type"] == "choice":
                    if any(isinstance(v, (list, dict)) for v in question["criteria"].values()):
                        descs += 1
    for topic, spec in sorted(MEDIUM.items()):
        medium[topic] = spec[0]
    for topic in ROWS:
        row = [r for r in ROWS[topic] if r["slot"] == 10][0]
        value = row["labels"]["事实"]["noul"]
        if 0.35 <= value <= 0.65:
            mixed_uncertain += 1
    return {"array_states": arrays, "structured_instructions": instrs,
            "structured_candidate_descriptions": descs, "medium_slots": medium,
            "mixed_uncertain_noul": mixed_uncertain,
            "case_types": dict(Counter(r["review"]["case_type"] for rows in ROWS.values() for r in rows))}


