def write_drafts():
    """把 ALL 按命题分组写成 data/drafts/Txxxx.jsonl（每题 10 行，含 labels）。"""
    drafts = ROOT / 'data' / 'drafts'
    grouped = defaultdict(list)
    for row in ALL:
        grouped[row['topic_id']].append(row)
    assert sorted(grouped) == [f'T{num:04d}' for num in range(61, 81)], '命题范围必须为 T0061—T0080'
    for topic, rows in sorted(grouped.items()):
        rows.sort(key=lambda row: row['slot'])
        assert [row['sample_id'] for row in rows] == [f'{topic}-{slot:02d}' for slot in range(1, 11)]
        write_jsonl(drafts / f'{topic}.jsonl', rows)
    print(f'已写入 {len(grouped)} 个草稿，共 {len(ALL)} 条')


def publish():
    """逐题调用 finalize_shard；已存在的分片不覆盖，需要先核对。"""
    for num in range(61, 81):
        topic = f'T{num:04d}'
        draft = ROOT / 'data' / 'drafts' / f'{topic}.jsonl'
        subprocess.run([sys.executable, '-m', 'scripts.finalize_shard', str(draft)],
                       cwd=ROOT, check=True)


if __name__ == '__main__':
    write_drafts()
    if '--publish' in sys.argv:
        publish()
