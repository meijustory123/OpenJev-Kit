# Structured-state / structured-instruction / structured-candidate coverage.
ARRAY_STATE_TOPICS = {61, 63, 66, 68, 71, 72, 74, 76, 77, 80}
STRUCTURED_INSTRUCTION_TOPICS = {61, 63, 65, 67, 69, 71, 72, 74, 76, 78, 80}
STRUCTURED_CHOICE_TOPICS = {61, 62, 63, 64, 65, 66, 68, 70, 73, 75, 77, 79}

# Peak probabilities rotate so that no slot always produces the same vector.
CHOICE_PEAKS = (0.94, 0.91, 0.96, 0.88, 0.93, 0.97, 0.90, 0.95)
SCORE_VECTORS = (
    ([0.96, 0.04, 0.00], [0.06, 0.90, 0.04], [0.00, 0.03, 0.97]),
    ([0.93, 0.06, 0.01], [0.04, 0.88, 0.08], [0.01, 0.05, 0.94]),
    ([0.91, 0.08, 0.01], [0.09, 0.84, 0.07], [0.00, 0.06, 0.94]),
)

# 中档样本所在槽位在题内轮换，十个槽位各出现两次。
MEDIUM_SLOT = {61: 4, 62: 1, 63: 6, 64: 9, 65: 3, 66: 10, 67: 2, 68: 7, 69: 5, 70: 8,
               71: 1, 72: 4, 73: 3, 74: 6, 75: 9, 76: 10, 77: 2, 78: 7, 79: 5, 80: 8}


def add(num, rule, ci, choices, si, levels, cases, array=False):
    topic = f'T{num:04d}'
    medium = MEDIUM_SLOT[num]
    assert len(cases) == 10, topic
    assert 1 <= medium <= 10, topic
    for slot, case in enumerate(cases, 1):
        assert (slot == medium) == ('L' in case), f'{topic} 槽位{slot} 长样本标记不一致'
        content = case['L'] if slot == medium else case['s']
        state = ({'适用规则': rule, '当前记录': content} if num not in ARRAY_STATE_TOPICS else
                 [{'适用规则': rule}, {'当前记录': content}])
        questions, labels, evidence = {}, {}, {}
        if slot <= 4 or slot == 10:
            cr = dict(choices)
            if num in STRUCTURED_CHOICE_TOPICS:
                cr = {k: {'判定条件': v} for k, v in cr.items()}
            instruction = ({'判断目标': ci, '限制': '仅使用本条记录及适用规则。'}
                           if num in STRUCTURED_INSTRUCTION_TOPICS else ci)
            questions['类别'] = {'type': 'choice', 'instructions': instruction, 'criteria': cr}
            keys = list(cr)
            n = len(keys)
            target = keys[case['a']]
            peak = case.get('cp', CHOICE_PEAKS[(num + slot) % len(CHOICE_PEAKS)])
            if 'r' in case and n >= 3:
                # 易混类别：把可解释的相邻类别抬到高于其余干扰项，而不是让它们等权。
                runner_up = round((1 - peak) * 0.55, 3)
                rest = round((1 - peak - runner_up) / (n - 2), 3)
                probs = {key: rest for key in keys}
                probs[keys[case['r']]] = runner_up
                probs[target] = round(1 - rest * (n - 2) - runner_up, 3)
            else:
                other = round((1 - peak) / (n - 1), 3)
                probs = {key: other for key in keys}
                probs[target] = round(1 - other * (n - 1), 3)
            drift = 1 - sum(probs.values())
            if abs(drift) > 1e-9:
                probs[target] = round(probs[target] + drift, 6)
            labels['类别'] = {'probabilities': probs}
            evidence['类别'] = case['e'][0] if slot == 10 else case['e']
        if 5 <= slot <= 7 or slot == 10:
            questions['程度'] = {'type': 'score', 'instructions': si, 'criteria': levels}
            if 'sp' in case:
                values = case['sp']
            else:
                rank = case['b'] if slot == 10 else slot - 5
                values = SCORE_VECTORS[(num + slot) % len(SCORE_VECTORS)][rank]
            labels['程度'] = {'probabilities': {str(i): v for i, v in enumerate(values)}}
            evidence['程度'] = case['e'][1] if slot == 10 else case['e']
        if slot >= 8:
            questions['事实'] = {'type': 'noul', 'instructions': case['n']}
            default_noul = 0.96 + (num % 4) * 0.01 if slot == 8 else 0.05 - (num % 4) * 0.01
            labels['事实'] = {'noul': case.get('np', round(default_noul, 3))}
            evidence['事实'] = case['e'][2] if slot == 10 else case['e']
        ALL.append({'sample_id': f'{topic}-{slot:02d}', 'topic_id': topic, 'slot': slot,
                    'request': {'model': 'jev-latest', 'state': state, 'questions': questions},
                    'labels': labels, 'review': {'case_type': CASE_TYPES[slot], 'evidence': evidence,
                                                 'label_source': 'agent_synthetic'}})


